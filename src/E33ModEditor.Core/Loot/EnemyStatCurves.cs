internal static class EnemyStatCurves
{
    public static double Ratio(int fromLevel, int toLevel, string field, bool bossAtk)
    {
        var from = At(fromLevel, field, bossAtk);
        if (from <= 0) return 1;
        var to = At(toLevel, field, bossAtk);
        return to / from;
    }

    private static double At(int level, string field, bool bossAtk)
    {
        level = Math.Clamp(level, 1, 99);
        var i = level - 1;
        return field switch
        {
            "HP" => Hp[i],
            "PhysicalAttack" or "MagicalAttack" => bossAtk ? BossAtk[i] : Atk[i],
            "Speed" => Speed[i],
            "Experience" => Xp[i],
            "Chroma" => Chroma[i],
            _ => 1,
        };
    }

    /// <summary>Absolute Regular-curve value (see <see cref="At"/>).</summary>
    internal static double Value(int level, string field, bool bossAtk) => At(level, field, bossAtk);

