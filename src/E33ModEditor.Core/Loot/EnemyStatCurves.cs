/// <summary>
/// Normal-difficulty archetype curves (levels 1–99) used to retarget an
/// enemy's EnemyScaling from its catalog fight level to an area peer.
/// HP / Speed / XP / Chroma ratios match across Regular and Boss; PATK
/// uses the Boss curve for Boss/Alpha rows.
